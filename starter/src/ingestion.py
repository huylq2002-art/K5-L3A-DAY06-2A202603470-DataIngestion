"""Read and normalize source data - implemented for handbook corpus.

NOTE on PDF font encoding: PyMuPDF (fitz) cannot extract Vietnamese text from
PDFs generated with its own insert_text() using the built-in 'helv' font because
that font doesn't embed full Unicode glyphs for diacritics. As a result, extracted
text shows replacement characters (·) instead of Vietnamese letters.

FIX: We provide two loaders:
  - load_json(): Primary loader, reads from the JSON corpus (clean UTF-8 text).
    This is the authoritative source for embedding and retrieval.
  - load_pdf(): Secondary loader that works for PDFs with proper embedded Unicode
    fonts (e.g., generated by reportlab with TTF fonts, or scanned+OCR PDFs).
    For our generated PDF, text extraction quality is degraded; this is documented
    as a known limitation in the lab report.

The lab corpus file is data/handbook_sv_2025.json (source of truth) with the PDF
at data/handbook_sv_2025.pdf as the human-readable version.
"""
import json
import re
import unicodedata
from pathlib import Path
from .models import DocumentPage

import fitz  # PyMuPDF


def load_json(path: Path, document_id: str, source: str) -> list[DocumentPage]:
    """Load corpus pages from the JSON file (primary loader - clean UTF-8 text).

    The JSON file contains the same content as the PDF but with proper Unicode
    encoding. Each entry maps to one physical page with its section metadata.
    """
    with open(path, encoding="utf-8") as f:
        raw_pages = json.load(f)

    pages = []
    for entry in raw_pages:
        text = normalize_text(entry["text"])
        if len(text.strip()) < 50:
            print(f"[WARN] Page {entry['page']} has very short text ({len(text)} chars), skipping.")
            continue

        metadata = {
            "section": entry.get("section", "unknown"),
            "year": entry.get("year", 2025),
            "document_type": "quy_che_dao_tao",
            "audience": "sinh_vien",
        }

        pages.append(DocumentPage(
            document_id=document_id,
            source=source,
            page=entry["page"],
            text=text,
            metadata=metadata,
        ))

    print(f"[INFO] Loaded {len(pages)} pages from JSON corpus.")
    return pages


def load_pdf(path: Path, document_id: str, source: str) -> list[DocumentPage]:
    """Extract each physical page from PDF; keep its page number and source.

    Uses PyMuPDF (fitz) to extract text. Records pages with no extractable text.

    KNOWN LIMITATION: PDFs generated with fitz's built-in 'helv' font do not
    embed full Unicode glyphs; Vietnamese diacritics are replaced with '·'.
    Use load_json() for this corpus. This function is preserved for PDFs with
    proper embedded Unicode TTF fonts (e.g., from reportlab or external tools).
    """
    pages = []
    doc = fitz.open(str(path))
    empty_pages = []
    degraded_pages = []

    for page_num in range(len(doc)):
        fitz_page = doc[page_num]
        raw_text = fitz_page.get_text("text")

        if not raw_text or len(raw_text.strip()) < 20:
            empty_pages.append(page_num + 1)
            print(f"[WARN] Page {page_num + 1}: no/little extractable text.")
            continue

        normalized = normalize_text(raw_text)

        # Detect font encoding degradation: >15% replacement chars = degraded
        replacement_ratio = normalized.count('·') / max(len(normalized), 1)
        if replacement_ratio > 0.15:
            degraded_pages.append(page_num + 1)

        section = "unknown"
        section_match = re.search(r'\[([A-Z0-9_]+)\]', normalized)
        if section_match:
            section = section_match.group(1).lower()

        page_number = page_num + 1
        metadata = {
            "section": section,
            "year": 2025,
            "document_type": "quy_che_dao_tao",
            "audience": "sinh_vien",
        }

        pages.append(DocumentPage(
            document_id=document_id,
            source=source,
            page=page_number,
            text=normalized,
            metadata=metadata,
        ))

    doc.close()

    if empty_pages:
        print(f"[WARN] Empty pages (skipped): {empty_pages}")
    if degraded_pages:
        print(f"[WARN] Degraded pages (font encoding issue, {len(degraded_pages)} pages): {degraded_pages[:5]}...")
        print(f"[WARN] Use load_json() instead for clean text extraction.")
    else:
        print(f"[INFO] All {len(pages)} pages extracted from PDF successfully.")

    return pages


def normalize_text(text: str) -> str:
    """Normalize Unicode and whitespace without discarding useful structure."""
    # NFC Unicode normalization
    text = unicodedata.normalize("NFC", text)

    # Replace various dash/hyphen variants with standard hyphen
    text = text.replace("\u2013", "-").replace("\u2014", "-").replace("\u2010", "-")

    # Replace fancy quotes with standard quotes
    text = text.replace("\u201c", '"').replace("\u201d", '"')
    text = text.replace("\u2018", "'").replace("\u2019", "'")

    # Collapse multiple spaces to single (but preserve newlines for structure)
    text = re.sub(r'[ \t]+', ' ', text)

    # Collapse more than 2 consecutive newlines into 2
    text = re.sub(r'\n{3,}', '\n\n', text)

    # Strip leading/trailing whitespace per line
    lines = [line.strip() for line in text.splitlines()]
    text = '\n'.join(lines)

    # Remove any null bytes or control characters (except newline/tab)
    text = re.sub(r'[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]', '', text)

    return text.strip()
